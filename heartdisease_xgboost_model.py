print("Feature Count:", len(feature_names))

mean_importance = np.abs(shap_values_array).mean(axis=0).mean(axis=1)

"""Explanation:

mean(axis=0) → average over samples → (features, classes)

mean(axis=1) → average over classes → (features,)
"""

